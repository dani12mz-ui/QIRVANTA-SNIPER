"""Assemble RC1, its strategy audit, and an optional pinned S5 reference probe."""

import argparse
import hashlib
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
EXPERIMENTAL = ROOT / "unified" / "experimental"
PARTS = EXPERIMENTAL / "gold_pro_rc1"
RELEASE = ROOT / "releases" / "gold-pro-rc1"
BASELINE = "a920f15370b536f19def0205b21915e1a3d2e4ed4c76c80bd22f5e8aa6bf7c10"
WICK = "b662883f93c8f67e92227592ec4168b55ebd8475a7b227cab78ba0fba49b636b"
NATIVE_START = "// One native portfolio. The broker emulator owns fills;"
DISPLAY_START = "// Presentation only: admission, orders and fills belong to the native adapter."


def pinned(path, expected):
    content = path.read_bytes()
    if hashlib.sha256(content).hexdigest() != expected:
        raise ValueError(f"Pinned source changed: {path}")
    return content.decode("utf-8").replace("\r\n", "\n")


def remove_between(source, start, end):
    left, separator, rest = source.partition(start)
    _, final_separator, right = rest.partition(end)
    if not separator or not final_separator:
        raise ValueError(f"Source anchors missing: {start!r}, {end!r}")
    return left + end + right


def freeze_inputs(source):
    """Replace single-line baseline inputs with their exact first arguments."""
    pattern = re.compile(r"^(\w+ \w+ = )input\.\w+\(")
    output = []
    for line in source.splitlines(keepends=True):
        match = pattern.match(line)
        if not match:
            if "input." in line and not line.lstrip().startswith("//"):
                raise ValueError(f"Unexpected baseline input: {line}")
            output.append(line)
            continue
        start = match.end()
        depth = 0
        in_string = False
        escaped = False
        first_comma = None
        for index in range(start, len(line)):
            char = line[index]
            if in_string:
                if char == '"' and not escaped:
                    in_string = False
                escaped = char == "\\" and not escaped
            elif char == '"':
                in_string = True
            elif char in "([":
                depth += 1
            elif char in ")]":
                if depth == 0:
                    break
                depth -= 1
            elif char == "," and depth == 0 and first_comma is None:
                first_comma = index
        else:
            raise ValueError(f"Multiline baseline input: {line}")
        output.append(match[1] + line[start:first_comma or index] + line[index + 1:])
    return "".join(output)


def wick_observer():
    source = pinned(EXPERIMENTAL / "gold_wick" / "engine.pineinc", WICK)
    source = remove_between(source, "string wfEntryPolicy", "bool wfSupported")
    source = source.replace(
        "bool wfAuditBar = wfAudit and wfConfirmed and time_close >= wfAuditStart and time_close <= wfAuditEnd",
        "const bool wfAuditBar = false",
    )
    source = remove_between(source, "type WickPlan", "f_wfNumber")
    source = remove_between(source, "f_wfRound(", "var WickFormation wfActive")
    source = remove_between(source, "if not na(wfOfferedPlan)", "bool wfIntrabarPending")
    source = "\n".join(
        line for line in source.splitlines()
        if not any(name in line for name in ("WickPlan ", "wfOfferedPlan :="))
    )
    return source + "\n"


def assemble():
    source = pinned(EXPERIMENTAL / "QIRVANTA_SNIPER_PREMIUM_V2.pine", BASELINE)
    strategy_header = source.splitlines()[2]
    start = source.index("const string CORE_SHA256")
    source = source[start:source.index(DISPLAY_START)]
    source = source.replace('tvStrategyMode = input.string("S0",', 'tvStrategyMode = input.string("S5",', 1)
    frozen = freeze_inputs(source)
    header = "//@version=6\n// Generated by unified/tools/build_gold_pro_rc1.py.\n"
    indicator = (
        'indicator("QIRVANTA GOLD PRO RC1", shorttitle="GOLD PRO RC1", overlay=true, '
        'behind_chart=false, max_labels_count=42, max_lines_count=16, max_boxes_count=6, '
        'max_bars_back=1000, calc_bars_count=1200)\n'
    )
    def part(name):
        return (PARTS / f"{name}.pineinc").read_text(encoding="utf-8") + "\n"

    def strategy(name, short, body):
        declaration = re.sub(r'^strategy\("[^"]+", shorttitle="[^"]+"', f'strategy("{name}", shorttitle="{short}"', strategy_header)
        return header + declaration + "\n" + body + part("bridge") + part("native")

    primary = (
        header + indicator + frozen[:frozen.index(NATIVE_START)] + part("bridge")
        + wick_observer() + part("state") + part("display") + part("alerts")
    )
    audit = strategy("QIRVANTA GOLD PRO RC1 · Audit", "RC1 AUDIT", frozen)
    reference = strategy("Pinned Premium V2 · S5 Reference", "PINNED S5", source)
    return primary, audit, reference


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--reference-out", type=Path)
    args = parser.parse_args()
    primary, audit, reference = assemble()
    RELEASE.mkdir(parents=True, exist_ok=True)
    files = {
        RELEASE / "QIRVANTA_GOLD_PRO_RC1.pine": primary,
        RELEASE / "QIRVANTA_GOLD_PRO_RC1_AUDIT.pine": audit,
    }
    if args.reference_out:
        files[args.reference_out] = reference
    for path, content in files.items():
        expected = content.encode("utf-8")
        if args.check:
            if not path.exists() or path.read_bytes() != expected:
                raise SystemExit(f"Generated file is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)


if __name__ == "__main__":
    main()
