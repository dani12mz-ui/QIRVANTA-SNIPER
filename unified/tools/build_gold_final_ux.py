"""Generate the final GOLD PRO layout from the pinned Precision trading engine."""

import argparse

from unified.tools import build_gold_precision as precision


COMPONENTS = precision.EXPERIMENTAL / "gold_final_ux"
PRECISION_SHA = {
    "indicator": "cdcfcb7713d86a3f06adfe0dab0ef089bb5c51e61e9a6499f4634af92ae835b5",
    "strategy": "b0bee6812d8e4d1079f4f7680aed864c505d13fe81631f2ce32d9eee1e86f14c",
}
TARGETS = {
    "indicator": precision.EXPERIMENTAL / "QIRVANTA_GOLD_PRO_FINAL_INTELLIGENCE.pine",
    "strategy": precision.EXPERIMENTAL / "QIRVANTA_GOLD_PRO_FINAL_STRATEGY.pine",
}
TITLES = {
    "indicator": ("QIRVANTA GOLD PRO Final Intelligence", "Q FINAL Intel"),
    "strategy": ("QIRVANTA GOLD PRO Final Strategy", "Q FINAL Risk"),
}


def declaration(kind):
    previous = precision.declaration(kind)
    if kind == "indicator":
        previous = previous.replace("overlay=true,", "overlay=true, behind_chart=false,", 1)
    old_title, old_short = precision.TITLES[kind]
    title, short = TITLES[kind]
    return previous.replace(old_title, title, 1).replace(old_short, short, 1)


def fragment(name):
    return (COMPONENTS / name).read_text(encoding="utf-8").strip()


def build(kind):
    previous = precision.TARGETS[kind].read_bytes()
    if precision.digest(previous) != PRECISION_SHA[kind] or previous != precision.build(kind):
        raise ValueError(f"Precision {kind} differs from its pinned source")
    blocks = [
        "//@version=6\n" + declaration(kind) + "\n// Generated by unified.tools.build_gold_final_ux.",
        precision.pinned_engine(kind),
        precision.fragment(f"{kind}_view.pineinc"),
        fragment("dashboard.pineinc"),
        fragment("geometry.pineinc"),
        fragment("markers.pineinc"),
    ]
    return ("\n\n".join(blocks) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--kind", choices=tuple(TARGETS))
    args = parser.parse_args()
    for kind in (args.kind,) if args.kind else TARGETS:
        target = TARGETS[kind]
        data = build(kind)
        if args.check:
            if not target.is_file() or target.read_bytes() != data:
                parser.error(f"{target.name} differs from its sources")
        else:
            target.write_bytes(data)
        engine_hash = precision.digest(precision.pinned_engine(kind).encode("utf-8"))
        print(f"{target.name} sha256={precision.digest(data)} engine_sha256={engine_hash} bytes={len(data)}")


if __name__ == "__main__":
    main()
