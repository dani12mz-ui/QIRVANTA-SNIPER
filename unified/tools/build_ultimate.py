"""Build the separate Ultimate strategy and optionally an observation-only Pine buffer."""

import argparse
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
CHAMPION_COMMIT = 'c2212d7b7e0b4b7ea4be64c1fb3c9f7b33fa0f71'
CHAMPION_SHA = '92307768be68946dc87cbe4ea45a8b5e32446fd3b7a0c1a38dce40dffe358be3'
OUTPUT = ROOT / 'unified/experimental/QIRVANTA_ULTIMATE_EXPERIMENTAL.pine'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f'Expected one baseline anchor: {old}')
    return source.replace(old, new, 1)


def assemble(champion):
    if sha(champion) != CHAMPION_SHA:
        raise ValueError('Unexpected champion bytes')
    source = champion.decode('utf-8')
    source = replace_once(source, 'strategy("QIRVANTA Обединен", shorttitle="QIRV ONE"',
                          'strategy("QIRVANTA Ultimate Experimental", shorttitle="QIRV LAB"')
    source = replace_once(source, '// Generated by tools/build.py. Exact-hash validation evidence: reports/ACCEPTANCE.json.',
                          '// Generated by tools/build_ultimate.py from pinned champion c2212d7. Experimental only.')
    source = replace_once(source, 'bool alertsEnabled = input.bool(true,', 'bool alertsEnabled = input.bool(false,')
    source = replace_once(source, '    // A confirmed technical candidate is not automatically an admitted plan or an executed trade.', '''    // Only a selected FAST plan is eligible for the optional experimental veto.
    if ultimateF1 and nativeAdmissionReason == "" and not na(selectedNativePlan) and selectedNativePlan.family == 2
        float candleRange = high - low
        float signedBody = selectedNativePlan.side * (close - open)
        if na(candleRange) or na(signedBody) or candleRange <= 0 or signedBody < 0.55 * candleRange
            nativeAdmissionReason := "F1 · недостатъчно тяло в посоката на пробива"
    // A confirmed technical candidate is not automatically an admitted plan or an executed trade.''')
    source = replace_once(source, '// Presentation only: admission, orders and fills belong to the native adapter.', '''// Presentation only: admission, orders and fills belong to the native adapter.
f_ultimateR(float entry, float initialStop, float target, int side) =>
    float initialRisk = side * (entry - initialStop)
    float reward = side * (target - entry)
    not na(initialRisk) and not na(reward) and initialRisk > 0 and reward > 0 ? str.tostring(reward / initialRisk, "0.00") + "R" : "—"''')
    source = replace_once(source, '        string freshness = shownActive ?', '''        if shownActive
            targetText := "TP1 " + f_price(shownPlan.tp1) + " · " + f_ultimateR(shownEntry, shownInitialStop, shownPlan.tp1, shownPlan.side) + "\\nTP2 " + f_price(shownPlan.tp2) + " · " + f_ultimateR(shownEntry, shownInitialStop, shownPlan.tp2, shownPlan.side) + "\\nTP3 " + f_price(shownPlan.tp3) + " · " + f_ultimateR(shownEntry, shownInitialStop, shownPlan.tp3, shownPlan.side)
            planTip += "\\nR:R спрямо началния SL и " + (shownPending ? "ориентира" : "наблюдаваната симулирана цена") + ". Без разходите."
        string freshness = shownActive ?''')
    marker = '// BEGIN CANONICAL CORE '
    core_header = source.index(marker)
    core_start = source.index('\n', core_header) + 1
    core_end = source.index('// END CANONICAL CORE', core_start)
    parent_digest = source[core_header + len(marker):core_start - 1]
    candidate_digest = sha(source[core_start:core_end].encode('utf-8'))
    source = replace_once(source, f'CORE_SHA256 = "{parent_digest}"', f'CORE_SHA256 = "{candidate_digest}"')
    source = replace_once(source, marker + parent_digest, marker + candidate_digest)
    source = source[:core_header] + 'bool ultimateF1 = input.bool(false, "F1 · тяло на FAST свещ ≥ 55%", group="ULTIMATE / ЕКСПЕРИМЕНТ", display=display.none)\n' + source[core_header:]
    return source.encode('utf-8')


def observation(source):
    with tempfile.TemporaryDirectory() as temporary:
        probe = Path(temporary) / 'champion.txt'
        subprocess.run([sys.executable, '-B', str(ROOT / 'unified/tools/make_ui_probe.py'), str(probe)],
                       check=True, capture_output=True, cwd=ROOT)
        raw = probe.read_bytes()
    champion_size = len(champion_bytes())
    if sha(raw[:champion_size]) != CHAMPION_SHA:
        raise ValueError('Unexpected observer prefix')
    appendix = raw[champion_size:].decode('utf-8')
    appendix = replace_once(appendix, CHAMPION_SHA, sha(source))
    appendix = replace_once(appendix, '"ui_only|" + runModel', '(ultimateF1 ? "ultimate_f1_on|" : "ultimate_f1_off|") + runModel')
    appendix = replace_once(appendix, 'timeframe.in_seconds() != 900', '(timeframe.in_seconds() != 900 or syminfo.tickerid != "OANDA:XAUUSD")')
    return source + appendix.encode('utf-8')


def champion_bytes():
    return (ROOT / 'unified/QIRVANTA_UNIFIED.pine').read_bytes()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    actions = parser.add_mutually_exclusive_group(required=True)
    actions.add_argument('--build', action='store_true')
    actions.add_argument('--check', action='store_true')
    actions.add_argument('--observer', type=Path)
    args = parser.parse_args()
    source = assemble(champion_bytes())
    if args.build:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(source)
    elif OUTPUT.read_bytes() != source:
        raise SystemExit('Experimental output drifted')
    if args.observer:
        if args.observer.suffix != '.txt':
            raise ValueError('Use a new temporary .txt for the observer')
        with args.observer.open('xb') as stream:
            stream.write(observation(source))
    print(f'{OUTPUT.name} sha256={sha(source)}')


if __name__ == '__main__':
    main()
