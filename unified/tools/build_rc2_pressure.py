"""Build the RC2 pressure indicator and optional disposable native QA scripts."""

import argparse
from datetime import datetime
import re
from pathlib import Path

import build_gold_pro_rc1 as rc1
from build_gold_pro_rc2 import RELEASE, replace_once


PARTS = rc1.EXPERIMENTAL / "gold_pro_rc2_pressure"
OUTPUT = rc1.ROOT / "research" / "rc2-pressure-meter" / "QIRVANTA_GOLD_PRO_RC2_PRESSURE.pine"
BASE_NAME = "QIRVANTA GOLD PRO RC2 PREMIUM EDITION"
BASE_SHORT = "GOLD PRO RC2"
FEATURE_NAME = "QIRVANTA GOLD PRO RC2 · Pressure"
FEATURE_SHORT = "RC2 PRESSURE"
AUDIT_NAME = "QIRVANTA GOLD PRO RC2 · Audit"
START_DISPLAY = "// Presentation reads the frozen decision and observation streams."
START_ALERTS = 'bool rcAlertWatch = input.bool'
BASES = (
    ("QIRVANTA_GOLD_PRO_RC2.pine", "20551f9e06a4997257dcae035a6ec20c9bd93d998dd79c5dc6276edd47969de1"),
    ("QIRVANTA_GOLD_PRO_RC2_AUDIT.pine", "4ba04321a9ef5456e8fc61aa2b5b3ab6c44398a62b18e31b3041d9dda530d42b"),
)


def part(name):
    return (PARTS / f"{name}.pineinc").read_text(encoding="utf-8").rstrip() + "\n"


def rename(source, old_name, old_short, name, short):
    return replace_once(source, f'"{old_name}", shorttitle="{old_short}"',
                        f'"{name}", shorttitle="{short}"')


def presentation(source):
    swaps = (
        ("table.new(rcViewPosition, 6, 22", "table.new(rcViewPosition, 12, 26"),
        ("table.cell(rcViewTable, col, row", "table.cell(rcViewTable, col * 2, row"),
        ("table.merge_cells(rcViewTable, 0, row, 5, row)", "table.merge_cells(rcViewTable, 0, row, 11, row)"),
        ("table.merge_cells(rcViewTable, 0, row, 2, row)", "table.merge_cells(rcViewTable, 0, row, 5, row)"),
        ("table.merge_cells(rcViewTable, 3, row, 5, row)", "table.merge_cells(rcViewTable, 6, row, 11, row)"),
        ("table.merge_cells(rcViewTable, col, row, col + 1, row)",
         "table.merge_cells(rcViewTable, col * 2, row, (col + 2) * 2 - 1, row)"),
        ("\nif barstate.isfirst\n    for row", "\n" + part("widget") + "\nif barstate.isfirst\n    for row"),
        ("\nif rcViewRefresh\n    for col = 0 to 5",
         "\n    if rcPressureShow\n        f_rcPressureWidgetLayout()\n\nif rcViewRefresh\n    for col = 0 to 11"),
        ("width=rcViewColumn, height=0.01", "width=rcViewColumn / 2, height=0.01"),
        ('bool rcViewMinimal = rcPreset == "MINIMAL"', 'bool rcViewMinimal = rcPreset == "MINIMAL" or rcPreset == "COMPACT"'),
    )
    for old, new in swaps:
        source = replace_once(source, old, new)
    source, clears = re.subn(r"(table\.clear\(rcViewTable, 0, \d+, )5,", r"\g<1>11,", source)
    if clears != 7:
        raise ValueError("Pinned dashboard clear layout changed")
    return source.rstrip() + "\n    if rcPressureShow\n        f_rcPressureWidget()\n\n"


def build_indicator(base):
    base = rename(base, BASE_NAME, BASE_SHORT, FEATURE_NAME, FEATURE_SHORT)
    base = replace_once(base, "// Generated by unified/tools/build_gold_pro_rc2.py.",
                        "// Generated by unified/tools/build_rc2_pressure.py from pinned RC2.")
    base = replace_once(base, 'options=["PREMIUM", "MINIMAL", "MOBILE", "FULL AUDIT"]',
                        'options=["PREMIUM", "MINIMAL", "COMPACT", "MOBILE", "FULL AUDIT"]')
    core, display = base.split(START_DISPLAY, 1)
    display, alerts = display.split(START_ALERTS, 1)
    return core + part("meter") + "\n" + presentation(START_DISPLAY + display) + START_ALERTS + alerts


def qa_script(source, start, end, bars, s5, journal=True, pressure=False, compare=False, weighted=False):
    if bars != 1200:
        source = replace_once(source, "calc_bars_count=1200", f"calc_bars_count={bars}")
    if journal:
        source = replace_once(source, 'input.bool(false, "Export RC2 QA journal"',
                              'input.bool(true, "Export RC2 QA journal"')
    for kind, value in (("start", start), ("end", end)):
        pattern = rf'input\.time\(timestamp\("[^"]+"\), "QA {kind} UTC"'
        source, changes = re.subn(pattern, f'input.time({value}, "QA {kind} UTC"', source)
        if changes != 1:
            raise ValueError(f"Pinned QA {kind} changed")
    if s5:
        source = replace_once(source, 'input.string(RC2_AUDIT_FIXED, "Audit stop policy"',
                              'input.string(RC2_AUDIT_S5, "Audit stop policy"')
    for enabled, name in ((pressure, "rcPressureQa"), (compare, "rcPressureCompare"), (weighted, "rcPressureWeighted")):
        if enabled:
            source, changes = re.subn(rf"(\b{name} = input\.bool\()false\b", r"\g<1>true", source)
            if changes != 1:
                raise ValueError(f"Missing pressure input: {name}")
    return source


def utc_ms(value):
    date = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if date.tzinfo is None:
        raise argparse.ArgumentTypeError("An explicit UTC offset is required")
    return int(date.timestamp() * 1000)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--native-dir", type=Path)
    parser.add_argument("--qa-start", type=utc_ms, default="2026-11-10T00:00:00Z")
    parser.add_argument("--qa-end", type=utc_ms, default="2026-11-11T16:30:00Z")
    parser.add_argument("--bars", type=int, default=1200)
    parser.add_argument("--s5", action="store_true")
    parser.add_argument("--baseline-only", action="store_true")
    args = parser.parse_args()
    if args.bars < 1 or args.qa_start > args.qa_end:
        parser.error("Invalid bar count or QA period")
    if args.baseline_only and not args.native_dir:
        parser.error("--baseline-only needs --native-dir")
    base, audit = (rc1.pinned(RELEASE / filename, sha) for filename, sha in BASES)
    feature = None if args.baseline_only else build_indicator(base)
    if args.check:
        if feature is None or not OUTPUT.is_file() or OUTPUT.read_bytes() != feature.encode("utf-8"):
            raise SystemExit(f"Generated file is stale: {OUTPUT}")
    elif feature is not None and not args.native_dir:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(feature.encode("utf-8"))
    if args.native_dir:
        args.native_dir.mkdir(parents=True, exist_ok=True)
        probes = {
            "baseline_indicator": (rename(base, BASE_NAME, BASE_SHORT, "Pressure QA · Baseline Indicator", "PR BASE I"), {}),
            "baseline_audit": (rename(audit, AUDIT_NAME, "RC2 AUDIT", "Pressure QA · Baseline Audit", "PR BASE A"), {"s5": args.s5}),
        }
        if feature is not None:
            probes.update({
                "feature_indicator": (rename(feature, FEATURE_NAME, FEATURE_SHORT, "Pressure QA · Feature Indicator", "PR METER I"), {"pressure": True, "compare": True}),
                "feature_audit": (rename(audit, AUDIT_NAME, "RC2 AUDIT", "Pressure QA · Feature Audit", "PR METER A")
                                  + "\nconst bool rcReview = false\nconst int rcReviewAt = 0\n" + part("meter"), {"s5": args.s5, "compare": True}),
                "pressure_tick": (rename(feature, FEATURE_NAME, FEATURE_SHORT, "Pressure QA · Tick", "PR TICK"), {"journal": False, "pressure": True, "compare": True, "weighted": True}),
            })
        for name, (source, options) in probes.items():
            options.setdefault("s5", False)
            result = qa_script(source, args.qa_start, args.qa_end, args.bars, **options)
            (args.native_dir / f"{name}.pine").write_bytes(result.encode("utf-8"))


if __name__ == "__main__":
    main()
