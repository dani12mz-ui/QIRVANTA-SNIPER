"""Build the Gold Pro Precision & Risk visuals on the pinned Gold Pro engine."""

import argparse
import hashlib
from pathlib import Path

from unified.tools import build_gold_pro


EXPERIMENTAL = build_gold_pro.EXPERIMENTAL
COMPONENTS = EXPERIMENTAL / "gold_precision"
BASELINE_SHA = {
    "indicator": "2b42001c6b5135dbae5a3d660a8b465e3e8895bbcc9ed438670ec455079acc1a",
    "strategy": "5c8ece0060579956876899bd544fa0aee64dea9ac044fffa276a124c8161f655",
}
TARGETS = {
    "indicator": EXPERIMENTAL / "QIRVANTA_GOLD_PRO_PRECISION_INTELLIGENCE.pine",
    "strategy": EXPERIMENTAL / "QIRVANTA_GOLD_PRO_PRECISION_STRATEGY.pine",
}
TITLES = {
    "indicator": ("QIRVANTA GOLD PRO Precision Intelligence", "Q PREC Intel"),
    "strategy": ("QIRVANTA GOLD PRO Precision & Risk", "Q PREC Risk"),
}
LAYOUT_LIMITS = ", max_lines_count=12, max_labels_count=60, max_boxes_count=4"


def fragment(name):
    return (COMPONENTS / name).read_text(encoding="utf-8").strip()


def digest(data):
    return hashlib.sha256(data).hexdigest()


def declaration(kind):
    original = build_gold_pro.DECLARATIONS[kind]
    title, short = TITLES[kind]
    old_title, old_short = (
        ("QIRVANTA GOLD PRO Intelligence", "Q GOLD Intel")
        if kind == "indicator" else ("QIRVANTA GOLD PRO Strategy", "Q GOLD Pro")
    )
    renamed = original.replace(old_title, title, 1).replace(old_short, short, 1)
    return renamed.removesuffix(")") + LAYOUT_LIMITS + ")"


def pinned_engine(kind):
    original = build_gold_pro.TARGETS[kind].read_bytes()
    if digest(original) != BASELINE_SHA[kind] or original != build_gold_pro.build(kind):
        raise ValueError(f"Original Gold Pro {kind} differs from the pinned source")
    generated = original.decode("utf-8")
    marker = "\n\n" + build_gold_pro.fragment("dashboard.pineinc") + "\n"
    if not generated.endswith(marker):
        raise ValueError("Could not locate the original presentation boundary")
    engine = generated.removesuffix(marker)
    old_header = "//@version=6\n" + build_gold_pro.DECLARATIONS[kind] + "\n// Generated by unified.tools.build_gold_pro."
    if not engine.startswith(old_header + "\n\n"):
        raise ValueError("Unexpected original declaration")
    return engine.removeprefix(old_header + "\n\n")


def build(kind):
    blocks = [
        "//@version=6\n" + declaration(kind) + "\n// Generated by unified.tools.build_gold_precision.",
        pinned_engine(kind),
        fragment(f"{kind}_view.pineinc"),
        fragment("dashboard.pineinc"),
        fragment("geometry.pineinc"),
        fragment("markers.pineinc"),
    ]
    return ("\n\n".join(blocks) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--kind", choices=tuple(TARGETS))
    args = parser.parse_args()
    for kind in (args.kind,) if args.kind else TARGETS:
        target = TARGETS[kind]
        data = build(kind)
        if args.check:
            if not target.is_file() or target.read_bytes() != data:
                parser.error(f"{target.name} differs from its sources")
        else:
            target.write_bytes(data)
        print(f"{target.name} sha256={digest(data)} engine_sha256={digest(pinned_engine(kind).encode())} bytes={len(data)}")


if __name__ == "__main__":
    main()
