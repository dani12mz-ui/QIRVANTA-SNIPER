"""Build the self-contained Premium Pine release from the exact compiled baseline."""

import argparse
import hashlib
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]
BASELINE = ROOT / "unified/experimental/QIRVANTA_TRADINGVIEW_FINAL.pine"
OUTPUT = ROOT / "unified/experimental/QIRVANTA_SNIPER_PREMIUM.pine"
BASELINE_SHA = "bc7bf16cd988fa23832f75ff22ee421b198cafb95614c9445622ce7bc4cfe1c3"
CHAMPION = ROOT / "unified/QIRVANTA_UNIFIED.pine"
CHAMPION_SHA = "92307768be68946dc87cbe4ea45a8b5e32446fd3b7a0c1a38dce40dffe358be3"
PRESENTATION = b"// Presentation only: admission, orders and fills belong to the native adapter.\n"
ALERT_TAIL = b"// One close-time batch preserves all events; native fill observations are journal-only.\n"
FRAGMENTS = tuple(ROOT / "unified/src" / f"premium_{name}.pineinc" for name in ("zones", "dashboard"))
VISUAL_PATCHES = (
    ('strategy("QIRVANTA TradingView Final · Experimental", shorttitle="QIRV TV"',
     'strategy("QIRVANTA SNIPER PREMIUM · Experimental", shorttitle="QIRV PREMIUM"'),
    ("max_labels_count=160, max_lines_count=20, max_boxes_count=5",
     "max_labels_count=256, max_lines_count=192, max_boxes_count=80"),
    ('// Generated by tools/build_tradingview_final.py. Experimental Pine v6.',
     '// Generated by tools/build_sniper_premium.py from 6221eb63be02. Experimental Pine v6.'),
    ('string uiMode = input.string("STANDARD", "Плътност на изгледа", options=["MINIMAL", "STANDARD", "PRO", "DEBUG"]',
     'string uiMode = input.string("PREMIUM", "Плътност на изгледа", options=["MINIMAL", "STANDARD", "PRO", "DEBUG", "PREMIUM"]'),
    ('Нито един изглед не променя сделките.',
     'PREMIUM: риск, нива и симулирани изпълнения. Нито един изглед не променя сделките.'),
    ('bool displayEMAs = input.bool(true,', 'bool displayEMAs = input.bool(false,'),
    ('bool showHistoricalLabels = input.bool(false,', 'bool showHistoricalLabels = input.bool(true,'),
    ('int keepSignalLabels = input.int(20,', 'int keepSignalLabels = input.int(10,'),
)
RETIRED_VIEW_INPUTS = ("showZones", "keepLabels", "showContextLabels", "contextLabelSpacing", "showSetupLevel")
TRADE_WRITES = re.compile(rb"\bstrategy\.(?:entry|order|exit|close|close_all|cancel|cancel_all|risk\.\w+)\s*\(")


def sha(data):
    return hashlib.sha256(data).hexdigest()


def split(source):
    if source.count(PRESENTATION) != 1 or source.count(ALERT_TAIL) != 1:
        raise ValueError("Expected one engine/render seam and one alert seam")
    prefix, rest = source.split(PRESENTATION)
    view, tail = rest.split(ALERT_TAIL)
    return prefix, view, ALERT_TAIL + tail


def pinned_source():
    source = BASELINE.read_bytes()
    if sha(source) != BASELINE_SHA or sha(CHAMPION.read_bytes()) != CHAMPION_SHA:
        raise ValueError("A preserved Pine artifact differs from its pinned SHA-256")
    return source


def visual_prefix(prefix):
    for old, new in VISUAL_PATCHES:
        old, new = old.encode("utf-8"), new.encode("utf-8")
        if prefix.count(old) != 1:
            raise ValueError(f"Visual-only allowance must match once: {old!r}")
        prefix = prefix.replace(old, new, 1)
    for name in RETIRED_VIEW_INPUTS:
        symbol = rb"\b" + name.encode("ascii") + rb"\b"
        if len(re.findall(symbol, prefix)) != 1:
            raise ValueError(f"Retired view input has an engine consumer: {name}")
        prefix, n = re.subn(rb"^(?:bool|int) " + name.encode("ascii") + rb" = input\.[^\n]*\n", b"", prefix, flags=re.MULTILINE)
        if n != 1:
            raise ValueError(f"Retired view input declaration not found: {name}")
    return prefix


def verify_source(source):
    prefix, _, tail = split(pinned_source())
    candidate_prefix, view, candidate_tail = split(source)
    if candidate_prefix != visual_prefix(prefix) or candidate_tail != tail:
        raise ValueError("Engine or alert bytes changed outside the visual allowances")
    if TRADE_WRITES.search(view) or re.search(rb"\brequest\.[a-z_]+\s*\(", view):
        raise ValueError("Presentation may not submit orders or request new data")
    if any(re.search(rb"\b" + name.encode("ascii") + rb"\b", view) for name in RETIRED_VIEW_INPUTS):
        raise ValueError("Presentation uses a retired visual input")
    if len(re.findall(rb"^strategy\(", source, re.MULTILINE)) != 1:
        raise ValueError("The release must declare exactly one strategy")
    return {"baseline_sha256": BASELINE_SHA, "source_sha256": sha(source),
            "pinned_engine_prefix_sha256": sha(prefix), "alert_tail_sha256": sha(tail),
            "source_bytes": len(source), "source_lines": len(source.splitlines()),
            "presentation_bytes": len(view), "scope": "STATIC_SOURCE_GUARD_NOT_NATIVE_PARITY"}


def build():
    prefix, _, tail = split(pinned_source())
    view = b"\n\n".join(path.read_bytes().replace(b"\r\n", b"\n").strip() for path in FRAGMENTS)
    source = visual_prefix(prefix) + PRESENTATION + view + b"\n\n" + tail
    verify_source(source)
    return source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in bytes instead of writing")
    args = parser.parse_args()
    source = build()
    if args.check:
        if OUTPUT.read_bytes() != source:
            raise SystemExit(f"Stale generated source: {OUTPUT.name}")
    else:
        OUTPUT.write_bytes(source)
    print(f"{OUTPUT.name} sha256={sha(source)} bytes={len(source)} lines={len(source.splitlines())}")


if __name__ == "__main__":
    main()
