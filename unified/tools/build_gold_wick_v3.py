"""Assemble the V3 presentation around the original Wick v6 execution prefix."""

import argparse
from hashlib import sha256

from unified.tools import build_gold_wick as original


COMPONENTS = original.EXPERIMENTAL / "gold_wick_v3"
TARGETS = {
    "indicator": original.EXPERIMENTAL / "QIRVANTA_GOLD_WICK_V3_INTELLIGENCE.pine",
    "strategy": original.EXPERIMENTAL / "QIRVANTA_GOLD_WICK_V3_FORMATION_STRATEGY.pine",
}
BASE_SHA = {
    "indicator": "497e4973bdb707660547ede81cb36eb377cceb267970aae6d1d5599e59a8de6e",
    "strategy": "680dff2860c16d116a80029722948366099ee5d838ea837170217e634be681d9",
}
TITLES = {
    "indicator": ("QIRVANTA GOLD PRO · Wick Visual V3", "Q WICK V3"),
    "strategy": ("QIRVANTA GOLD PRO · Formation Visual V3", "Q RISK V3"),
}
BASE_TITLES = {
    "indicator": ("QIRVANTA GOLD PRO · Wick Intelligence", "Q WICK Intel"),
    "strategy": ("QIRVANTA GOLD PRO · Formation Research", "Q WICK Risk"),
}
DELIMITER = "// V3 PRESENTATION ONLY"


def declaration(kind):
    old_long, old_short = BASE_TITLES[kind]
    title, short = TITLES[kind]
    return (original.DECLARATIONS[kind].replace(old_long, title, 1).replace(old_short, short, 1)
            .replace("max_boxes_count=50, max_labels_count=80", "max_boxes_count=50, max_labels_count=80, max_lines_count=80"))


def fragment(name):
    return (COMPONENTS / f"{name}.pineinc").read_text(encoding="utf-8").strip()


def build(kind):
    baseline = original.TARGETS[kind].read_bytes()
    if sha256(baseline).hexdigest() != BASE_SHA[kind] or baseline != original.build(kind):
        raise ValueError(f"Wick baseline differs for {kind}")
    sections = [
        "//@version=6\n" + declaration(kind) + "\n// Generated by unified.tools.build_gold_wick_v3.",
        original.fragment("engine"),
        original.fragment(f"{kind}_execution"),
        DELIMITER,
        fragment("style"),
        fragment(f"{kind}_view"),
        fragment("view"),
        fragment("formations"),
        fragment("trade_geometry"),
        fragment("dashboard"),
    ]
    return ("\n\n".join(sections) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--kind", choices=tuple(TARGETS))
    args = parser.parse_args()
    for kind in (args.kind,) if args.kind else TARGETS:
        path = TARGETS[kind]
        rendered = build(kind)
        if args.check:
            if not path.is_file() or path.read_bytes() != rendered:
                parser.error(f"{path.name} differs from its source")
        else:
            path.write_bytes(rendered)
        print(f"{path.name} sha256={sha256(rendered).hexdigest()} bytes={len(rendered)}")


if __name__ == "__main__":
    main()
