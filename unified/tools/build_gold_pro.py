"""Generate the standalone Gold Pro Pine pair from shared components."""

import argparse
import hashlib
from pathlib import Path


EXPERIMENTAL = Path(__file__).resolve().parents[1] / "experimental"
COMPONENTS = EXPERIMENTAL / "gold_pro"
V22_CORE = EXPERIMENTAL / "v22/market_core.pineinc"
V22_CORE_SHA = "2492c1adeca3f7d555ce5e1a9f456c92d1e09e31b5b034081337be8775042f91"
TARGETS = {
    "indicator": EXPERIMENTAL / "QIRVANTA_GOLD_PRO_INTELLIGENCE.pine",
    "strategy": EXPERIMENTAL / "QIRVANTA_GOLD_PRO_STRATEGY.pine",
}
DECLARATIONS = {
    "indicator": 'indicator("QIRVANTA GOLD PRO Intelligence", shorttitle="Q GOLD Intel", overlay=true, max_bars_back=1000)',
    "strategy": '''strategy("QIRVANTA GOLD PRO Strategy", shorttitle="Q GOLD Pro", overlay=true, behind_chart=false,
     initial_capital=100000, currency=currency.USD, pyramiding=0, default_qty_type=strategy.fixed,
     default_qty_value=3, commission_type=strategy.commission.cash_per_contract, commission_value=0.175,
     slippage=2, backtest_fill_limits_assumption=1, calc_on_every_tick=false, calc_on_order_fills=false,
     process_orders_on_close=false, use_bar_magnifier=false, margin_long=100, margin_short=100, max_bars_back=1000)''',
}


def v22_models():
    source = V22_CORE.read_text(encoding="utf-8")
    if hashlib.sha256(source.encode()).hexdigest() != V22_CORE_SHA:
        raise ValueError("The pinned V2.2 market model source changed")
    support_start = source.index("bool v22Supported")
    support_end = source.index("float v22TR", support_start)
    source = source[:support_start] + "bool v22Supported = gpSupported\n" + source[support_end:]
    context_start = source.index("// Each requested value")
    context_end = source.index("bool v22HighPivot", context_start)
    aliases = """// GOLD PRO supplies confirmed finite-window higher-timeframe context.
f_v22Bias(float price, float fast, float slow) =>
    price > fast and fast > slow ? 1 : price < fast and fast < slow ? -1 : 0
int v22H1 = gpH1Side
int v22H4 = gpH4Side

"""
    source = source[:context_start] + aliases + source[context_end:]
    return source.replace("V2.2 models", "Gold Pro models").strip()


def fragment(name):
    return (COMPONENTS / name).read_text(encoding="utf-8").strip()


def shared_source():
    return "\n\n".join([
        fragment("market_data.pineinc"),
        v22_models(),
        fragment("signals.pineinc"),
        fragment("opportunity.pineinc"),
        fragment("planner.pineinc"),
    ])


def build(kind):
    runtime = "observation.pineinc" if kind == "indicator" else "simulation.pineinc"
    return ("\n\n".join([
        "//@version=6\n" + DECLARATIONS[kind] + "\n// Generated by unified.tools.build_gold_pro.",
        shared_source(),
        fragment(runtime),
        fragment("dashboard.pineinc"),
    ]) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--kind", choices=tuple(TARGETS))
    args = parser.parse_args()
    for kind in (args.kind,) if args.kind else TARGETS:
        target = TARGETS[kind]
        data = build(kind)
        if args.check:
            if not target.is_file() or target.read_bytes() != data:
                parser.error(f"{target.name} differs from its sources")
        else:
            target.write_bytes(data)
        print(f"{target.name} sha256={hashlib.sha256(data).hexdigest()} bytes={len(data)}")


if __name__ == "__main__":
    main()
