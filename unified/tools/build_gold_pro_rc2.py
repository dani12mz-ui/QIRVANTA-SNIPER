"""Build the independent RC2 Pine v6 indicator and native audit strategy."""

import argparse
from pathlib import Path

import build_gold_pro_rc1 as rc1


PARTS = rc1.EXPERIMENTAL / "gold_pro_rc2"
RELEASE = rc1.ROOT / "releases" / "gold-pro-rc2"
RC1_INDICATOR = "e51308df4be72827dfdf4dc875a3dbea5b679a6bb859fe179909ba24c85e975f"
RC1_AUDIT = "dfb154e407d32cbfc90ac957788b54cfa5b4e2034421b4b3ac26abf039d59278"
BRIDGE_START = "// Read-only bridge from the pinned engine."
WICK_START = "// Independent confirmed-bar wick geometry"


def part(name):
    return (PARTS / f"{name}.pineinc").read_text(encoding="utf-8").rstrip() + "\n"


def replace_once(source, original, replacement):
    if source.count(original) != 1:
        raise ValueError(f"Expected exactly one pinned anchor: {original!r}")
    return source.replace(original, replacement, 1)


def native_adapter(source):
    prefix, native = source.split(rc1.NATIVE_START, 1)
    native = replace_once(
        native,
        'if note == "TP1" and not na(nativeRisk) and tvUsesBaselineLock',
        'if note == "TP1" and not na(nativeRisk) and tvUsesBaselineLock and rc2Parity',
    )
    native = replace_once(
        native,
        'if tvManagement and note == "TP1"',
        'if (tvManagement or rc2AuditMovesStop) and note == "TP1"',
    )
    native = replace_once(
        native,
        "        if nativeStopChanged\n",
        """        if rc2AuditMovesStop and nativeTvTP1 and not nativeTimeOrder and not na(nativeRisk)
            float fraction = rc2AuditLane == RC2_AUDIT_BE ? 0.0 : 0.25
            float protective = nativeEntry + nativePlan.side * nativeRisk * fraction
            float tightened = f_tvTighten(nativeStop, protective, nativePlan.side)
            if tightened != nativeStop
                nativeStop := tightened
                nativeStopChanged := true
        if nativeStopChanged
""",
    )
    native = replace_once(
        native,
        '    if nativeAdmissionReason == "" and tvManagementReason != ""',
        '''    if nativeAdmissionReason == "" and not f_rc2FilterPass(selectedNativePlan)
        nativeAdmissionReason := RC2_FILTER_REASON
    if nativeAdmissionReason == "" and tvManagementReason != ""''',
    )
    lane = """// Native audit keeps the pinned S5 fills available as an explicit parity control.
const string RC2_AUDIT_FIXED = "RC2 Fixed SL"
const string RC2_AUDIT_S5 = "S5 RAW Parity"
const string RC2_AUDIT_BE = "Experimental BE"
const string RC2_AUDIT_LOCK = "Experimental +0.25R"
string rc2AuditLane = input.string(RC2_AUDIT_FIXED, "Audit stop policy", options=[RC2_AUDIT_FIXED, RC2_AUDIT_S5, RC2_AUDIT_BE, RC2_AUDIT_LOCK], group="RC2 AUDIT", display=display.none)
bool rc2Parity = rc2AuditLane == RC2_AUDIT_S5
bool rc2AuditMovesStop = rc2AuditLane == RC2_AUDIT_BE or rc2AuditLane == RC2_AUDIT_LOCK
"""
    return prefix + lane + part("experiments") + "\n" + rc1.NATIVE_START + native


def assemble():
    primary = rc1.pinned(rc1.RELEASE / "QIRVANTA_GOLD_PRO_RC1.pine", RC1_INDICATOR)
    audit = rc1.pinned(rc1.RELEASE / "QIRVANTA_GOLD_PRO_RC1_AUDIT.pine", RC1_AUDIT)
    primary_core, tail = primary.split(BRIDGE_START, 1)
    audit_core, _ = audit.split(BRIDGE_START, 1)
    bridge = BRIDGE_START + tail.split(WICK_START, 1)[0]
    bridge = replace_once(bridge, '"Export RC1 QA journal"', '"Export RC2 QA journal"')
    header = "Generated by unified/tools/build_gold_pro_rc"
    primary_core = replace_once(primary_core, header + "1.py.", header + "2.py.")
    audit_core = replace_once(audit_core, header + "1.py.", header + "2.py.")
    primary_core = replace_once(
        primary_core, '"QIRVANTA GOLD PRO RC1", shorttitle="GOLD PRO RC1"',
        '"QIRVANTA GOLD PRO RC2 PREMIUM EDITION", shorttitle="GOLD PRO RC2"',
    )
    audit_core = replace_once(
        audit_core, '"QIRVANTA GOLD PRO RC1 · Audit", shorttitle="RC1 AUDIT"',
        '"QIRVANTA GOLD PRO RC2 · Audit", shorttitle="RC2 AUDIT"',
    )
    indicator = (
        primary_core + "const bool rc2Parity = false\n" + part("experiments") + "\n" + bridge
        + rc1.wick_observer() + part("state") + "\n" + part("display") + "\n" + part("alerts")
    )
    strategy = native_adapter(audit_core) + bridge + part("native")
    return {
        "QIRVANTA_GOLD_PRO_RC2.pine": indicator.rstrip() + "\n",
        "QIRVANTA_GOLD_PRO_RC2_AUDIT.pine": strategy.rstrip() + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    RELEASE.mkdir(parents=True, exist_ok=True)
    for name, text in assemble().items():
        path = RELEASE / name
        expected = text.encode("utf-8")
        if args.check:
            if not path.exists() or path.read_bytes() != expected:
                raise SystemExit(f"Generated file is stale: {path}")
        else:
            path.write_bytes(expected)


if __name__ == "__main__":
    main()
