"""Generate the standalone wick indicator and simulation from their shared Pine source."""

import argparse
from hashlib import sha256
from pathlib import Path


EXPERIMENTAL = Path(__file__).resolve().parents[1] / "experimental"
COMPONENTS = EXPERIMENTAL / "gold_wick"
TARGETS = {
    "indicator": EXPERIMENTAL / "QIRVANTA_GOLD_WICK_INTELLIGENCE.pine",
    "strategy": EXPERIMENTAL / "QIRVANTA_GOLD_WICK_FORMATION_STRATEGY.pine",
}
DECLARATIONS = {
    "indicator": (
        'indicator("QIRVANTA GOLD PRO · Wick Intelligence", shorttitle="Q WICK Intel", '
        "overlay=true, behind_chart=false, max_bars_back=300, max_boxes_count=50, max_labels_count=80)"
    ),
    "strategy": (
        'strategy("QIRVANTA GOLD PRO · Formation Research", shorttitle="Q WICK Risk", '
        "overlay=true, behind_chart=false, initial_capital=100000, currency=currency.USD,\n"
        "     pyramiding=0, default_qty_type=strategy.fixed, default_qty_value=3, "
        "commission_type=strategy.commission.cash_per_contract, commission_value=0.35,\n"
        "     slippage=2, backtest_fill_limits_assumption=1, calc_on_every_tick=false, "
        "calc_on_order_fills=false, process_orders_on_close=false, use_bar_magnifier=false,\n"
        "     margin_long=100, margin_short=100, max_bars_back=300, max_boxes_count=50, max_labels_count=80)"
    ),
}


def fragment(name):
    return (COMPONENTS / f"{name}.pineinc").read_text(encoding="utf-8").strip()


def build(kind):
    blocks = [
        "//@version=6\n" + DECLARATIONS[kind] + "\n// Generated by unified.tools.build_gold_wick.",
        fragment("engine"),
        fragment(f"{kind}_execution"),
        fragment("display"),
    ]
    return ("\n\n".join(blocks) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--kind", choices=tuple(TARGETS))
    args = parser.parse_args()
    for kind in (args.kind,) if args.kind else TARGETS:
        target = TARGETS[kind]
        data = build(kind)
        if args.check:
            if not target.is_file() or target.read_bytes() != data:
                parser.error(f"{target.name} differs from its sources")
        else:
            target.write_bytes(data)
        print(f"{target.name} sha256={sha256(data).hexdigest()} bytes={len(data)}")


if __name__ == "__main__":
    main()
