#!/usr/bin/env python3
"""Deterministic local assembly, not a Pine compiler. No network or publishing."""
from pathlib import Path
import hashlib, json
ROOT=Path(__file__).resolve().parents[1]
COMMON=['inputs','features','types_helpers','decision','paper_engine']

def text(name): return (ROOT/'src'/f'{name}.pineinc').read_text(encoding='utf-8').rstrip()+'\n'
def build():
    blocks='\n'.join(text(n) for n in COMMON)
    digest=hashlib.sha256(blocks.encode()).hexdigest()
    common='// BEGIN CANONICAL CORE '+digest+'\n'+blocks+'// END CANONICAL CORE\n'
    notice='// Generated by tools/build.py. Local research delivery; PINE_COMPILE_UNVERIFIED.\n// Not an AI model, not broker execution, no demonstrated trading edge.\n'
    versions={
        'QIRVANTA_SNIPER_PRO.pine':('indicator("QIRVANTA PRO | Наблюдение", shorttitle="QIRVANTA PRO", overlay=true, max_labels_count=100, max_lines_count=20, max_boxes_count=5, max_bars_back=1000)', 'indicator_adapter'),
        'QIRVANTA_SNIPER_VALIDATION.pine':('strategy("QIRVANTA | Native validation", shorttitle="QIRVANTA TEST", overlay=true, initial_capital=100000, currency=currency.USD, pyramiding=0, default_qty_type=strategy.fixed, default_qty_value=3, commission_type=strategy.commission.cash_per_contract, commission_value=0.175, slippage=2, calc_on_every_tick=false, calc_on_order_fills=false, process_orders_on_close=false, use_bar_magnifier=true, margin_long=100, margin_short=100, max_labels_count=100, max_lines_count=20, max_boxes_count=5, max_bars_back=1000)', 'native_adapter')
    }
    outputs={}
    for filename,(declaration,adapter) in versions.items():
        source='//@version=6\n'+declaration+'\n'+notice+common+'\n'+text(adapter)+'\n'+text('visual_alerts')
        if adapter=='indicator_adapter':
            source += '\nalertcondition(alertBuyNow, "QIRVANTA: технически BUY", "Завършен BUY модел. Невалидиран; не е брокерска поръчка. За цени използвай alert().")\nalertcondition(alertSellNow, "QIRVANTA: технически SELL", "Завършен SELL модел. Невалидиран; не е брокерска поръчка. За цени използвай alert().")\nalertcondition(alertRiskNow, "QIRVANTA: риск/отмяна", "Промяна в сценарий/статистика. Само анализ; провери подробното известие.")\n'
        (ROOT/filename).write_text(source,encoding='utf-8')
        outputs[filename]={'lines':len(source.splitlines()),'sha256':hashlib.sha256(source.encode()).hexdigest()}
    (ROOT/'reports/build.json').write_text(json.dumps({'canonical_core_sha256':digest,'outputs':outputs,'pine_compile':'UNVERIFIED'},ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(outputs,ensure_ascii=False,indent=2))
if __name__=='__main__': build()
